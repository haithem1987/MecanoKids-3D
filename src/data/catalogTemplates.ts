export function buildBlueprintFromSeed(seed: BlueprintSeed, stageNumber: number): VehicleBlueprint {
  const ls = seed.lengthScale ?? 1.0;
  const ws = seed.widthScale ?? 1.0;
  const accent = seed.accentColor ?? '#f59e0b';
  const meta = TIER_META[seed.tier];

  const drafts = buildArchetypeDrafts(seed.archetype, ls, ws).filter(
    (d) => d.minTier <= seed.tier,
  );

  const validIds = new Set(drafts.map((d) => d.id));

  const parts: PartSpec[] = drafts.map((d) => ({
    id: d.id,
    name: d.name,
    roleHint: d.roleHint,
    nameAr: d.nameAr,
    roleHintAr: d.roleHintAr,
    shape: d.shape,
    primaryColor: resolveColor(d.colorSlot, seed.primaryColor, seed.secondaryColor, accent),
    secondaryColor: resolveColor(d.secSlot, seed.primaryColor, seed.secondaryColor, accent),
    materialKind: d.materialKind,
    scale: d.scale,
    targetPos: d.targetPos,
    targetRot: d.targetRot,
    explodeOffset: d.explodeOffset,
    dependsOn: d.dependsOn.filter((dep) => validIds.has(dep)),
    snapRadius: meta.snap,
    animation: d.animation,
  }));

  return {
    id: seed.id,
    stageNumber,
    name: seed.name,
    nameAr: seed.nameAr,
    subtitle: seed.subtitle,
    subtitleAr: seed.subtitleAr,
    category: seed.category,
    tier: seed.tier,
    tierLabel: meta.fr,
    tierLabelAr: meta.ar,
    ageNote: meta.ageFr(parts.length),
    ageNoteAr: meta.ageAr(parts.length),
    discovery: seed.discovery,
    discoveryAr: seed.discoveryAr,
    parts,
  };
}
